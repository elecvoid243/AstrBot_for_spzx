"""Persist and fan out subagent progress independently of the parent reply."""

from __future__ import annotations

import asyncio
from collections import defaultdict
from copy import deepcopy

from sqlalchemy import func
from sqlalchemy.orm import defer
from sqlmodel import col, delete, select

from astrbot import logger
from astrbot.core.db.po import PlatformMessageHistory, WebChatSubagentRun


class SubagentProgress:
    """Own active traces, durable snapshots and bounded page subscriptions."""

    def __init__(self, db=None):
        """Initialize storage and subscriptions.

        Args:
            db: Optional isolated database; production uses the core database.
        """
        self.db = db
        self.active: dict[str, tuple[WebChatSubagentRun, object]] = {}
        self.subscribers: dict[str, set[asyncio.Queue]] = defaultdict(set)
        self.tasks: set[asyncio.Task] = set()
        self.pending: dict[str, asyncio.Task] = {}
        self.write_lock = asyncio.Lock()
        self.legacy_indexed: set[str] = set()
        self.deleted_sessions: set[str] = set()

    def database(self):
        """Return the injected or application database.

        Returns:
            Database owning WebChat sessions and their invocation snapshots.
        """
        if self.db is not None:
            return self.db
        from astrbot.core import db_helper

        return db_helper

    @staticmethod
    def metadata(row: WebChatSubagentRun, input_preview: str | None = None) -> dict:
        """Serialize the small navigation entry without its execution trace.

        Args:
            row: Stored invocation or its current in-memory snapshot.
            input_preview: Projected task preview when the trace is deferred.

        Returns:
            Navigation fields shared by lists, cards and terminal updates.
        """
        return {
            "subagent_run_id": row.run_id,
            "agent_name": row.agent_name,
            "agent_instance_id": row.agent_instance_id,
            "input_preview": str(
                input_preview
                if input_preview is not None
                else row.data.get("input_preview") or row.data.get("input_full") or ""
            )[:200],
            "background": row.background,
            "status": row.status,
            "cleaned": row.cleaned,
            "started_ts": row.started_ts,
            "revision": row.revision,
        }

    def publish(self, key: str, payload: dict) -> None:
        """Notify subscribers, requesting a fresh snapshot after overflow.

        Args:
            key: Session-list or individual-run subscription identity.
            payload: Metadata or sequenced event, without copying a long trace.
        """
        for queue in tuple(self.subscribers.get(key, ())):
            if queue.full():
                while not queue.empty():
                    queue.get_nowait()
                queue.put_nowait({"type": "resync"})
            else:
                queue.put_nowait(payload)

    async def persist(self, row: WebChatSubagentRun) -> None:
        """Serialize writes so a delayed partial snapshot cannot overwrite completion.

        Args:
            row: Live invocation whose latest revision must be saved.
        """
        async with self.write_lock:
            if row.session_id in self.deleted_sessions:
                return
            snapshot = WebChatSubagentRun.model_validate(row.model_dump())
            async with self.database().get_db() as session:
                await session.merge(snapshot)
                await session.commit()

    async def record(
        self, umo: str, instance_id: str, background: bool, data: dict
    ) -> dict:
        """Reduce, persist and publish progress without the parent response queue.

        Args:
            umo: Trusted WebChat runtime origin.
            instance_id: Identity of the agent configuration's current lifetime.
            background: Whether this invocation runs in the background.
            data: Structured subagent event generated by the runner.

        Returns:
            Compact current invocation metadata for the parent message card.
        """
        from astrbot.dashboard.services.chat_service import BotMessageAccumulator

        run_id = data["subagent_run_id"]
        kind = data["kind"]
        origin = umo.removeprefix("webchat:FriendMessage:")
        session_id = origin.rsplit("!", 1)[-1]
        if session_id in self.deleted_sessions:
            return {}
        if run_id not in self.active:
            row = WebChatSubagentRun(
                run_id=run_id,
                session_id=session_id,
                umo=umo,
                agent_instance_id=instance_id,
                agent_name=data["agent_name"],
                background=background,
                started_ts=data.get("ts", 0),
                data={},
            )
            self.active[run_id] = (row, BotMessageAccumulator())
        row, accumulator = self.active[run_id]
        accumulator.add_subagent_event(data)
        row.data = accumulator.subagent_runs[run_id]
        if kind == "started" and isinstance(
            data.get("payload", {}).get("configuration"), dict
        ):
            row.data["configuration"] = deepcopy(data["payload"]["configuration"])
        row.revision += 1
        row.status = row.data.get("status", "running")
        row.data.update(self.metadata(row))
        terminal = kind in {"completed", "failed", "timeout"}
        if kind == "started" or terminal:
            await self.persist(row)
        elif run_id not in self.pending:

            async def flush():
                try:
                    await asyncio.sleep(0.5)
                    if run_id in self.active:
                        await self.persist(row)
                except Exception:
                    logger.exception("Failed to persist subagent progress")
                finally:
                    self.pending.pop(run_id, None)

            task = asyncio.create_task(flush())
            self.pending[run_id] = task
            self.tasks.add(task)
            task.add_done_callback(self.tasks.discard)
        if session_id in self.deleted_sessions:
            return {}
        self.publish(
            f"run:{row.session_id}:{run_id}",
            {"type": "event", "data": deepcopy(data), "revision": row.revision},
        )
        if kind == "started" or terminal:
            self.publish(
                f"session:{row.session_id}",
                {"type": "changed", "data": self.metadata(row)},
            )
        if terminal:
            self.active.pop(run_id, None)
        return self.metadata(row)

    async def list_runs(self, session_id: str) -> list[dict]:
        """Read navigation entries, importing pre-upgrade traces as cleaned.

        Args:
            session_id: Session or thread already checked by the API owner gate.

        Returns:
            Compact invocation entries, newest first.
        """
        async with self.write_lock, self.database().get_db() as session:
            stored = (
                await session.execute(
                    select(
                        WebChatSubagentRun,
                        func.substr(
                            func.coalesce(
                                func.nullif(
                                    WebChatSubagentRun.data[
                                        "input_preview"
                                    ].as_string(),
                                    "",
                                ),
                                WebChatSubagentRun.data["input_full"].as_string(),
                                "",
                            ),
                            1,
                            200,
                        ),
                    )
                    .options(defer(WebChatSubagentRun.data))
                    .where(WebChatSubagentRun.session_id == session_id)
                )
            ).all()
            rows = [row for row, _ in stored]
            previews = {row.run_id: preview or "" for row, preview in stored}
            known = {row.run_id for row in rows}
            history = []
            if session_id not in self.legacy_indexed:
                history = (
                    (
                        await session.execute(
                            select(PlatformMessageHistory.content).where(
                                col(PlatformMessageHistory.platform_id).in_(
                                    ["webchat", "webchat_thread"]
                                ),
                                PlatformMessageHistory.user_id == session_id,
                            )
                        )
                    )
                    .scalars()
                    .all()
                )
            for content in history:
                for part in (
                    content.get("message", []) if isinstance(content, dict) else []
                ):
                    if not isinstance(part, dict) or part.get("type") != "subagent_run":
                        continue
                    run_id = part.get("subagent_run_id")
                    if not run_id or run_id in known or part.get("detached"):
                        continue
                    row = WebChatSubagentRun(
                        run_id=run_id,
                        session_id=session_id,
                        umo="",
                        agent_instance_id=part.get("agent_instance_id") or "",
                        agent_name=part.get("agent_name", "subagent"),
                        status=part.get("status", "completed")
                        if part.get("status") != "running"
                        else "failed",
                        cleaned=True,
                        started_ts=part.get("started_ts") or 0,
                        data=part,
                    )
                    session.add(row)
                    rows.append(row)
                    known.add(run_id)
            await session.commit()
            self.legacy_indexed.add(session_id)
            from astrbot.core.subagent_manager import SubAgentManager

            for row in rows:
                agent_session = SubAgentManager.get_session(row.umo)
                config = (
                    agent_session.subagents.get(row.agent_name)
                    if agent_session
                    else None
                )
                if (
                    not row.cleaned
                    and getattr(config, "instance_id", None) != row.agent_instance_id
                ):
                    row.cleaned = True
                    row.revision += 1
                    if row.status == "running" and row.run_id not in self.active:
                        row.status = "failed"
                    session.add(row)
            await session.commit()
        entries = {
            row.run_id: self.metadata(row, previews.get(row.run_id)) for row in rows
        }
        for row, _ in self.active.values():
            if row.session_id == session_id:
                entries[row.run_id] = self.metadata(row)
        return sorted(
            entries.values(), key=lambda item: item["started_ts"], reverse=True
        )

    async def get_run(self, session_id: str, run_id: str) -> dict | None:
        """Read one invocation only within its authorized parent session.

        Args:
            session_id: Owned WebChat session or thread.
            run_id: Requested invocation identity.

        Returns:
            Full snapshot, or None when the run belongs elsewhere or is missing.
        """
        live = self.active.get(run_id)
        if live and live[0].session_id == session_id:
            row = live[0]
        else:
            async with self.database().get_db() as session:
                row = (
                    await session.execute(
                        select(WebChatSubagentRun).where(
                            WebChatSubagentRun.session_id == session_id,
                            WebChatSubagentRun.run_id == run_id,
                        )
                    )
                ).scalar_one_or_none()
        if row is None:
            return None
        return {**deepcopy(row.data), **self.metadata(row)}

    async def get_configuration(self, session_id: str, run_id: str) -> dict | None:
        """Read an invocation's configuration without loading its execution trace.

        Args:
            session_id: Owned WebChat session or thread.
            run_id: Invocation within the authorized session.

        Returns:
            Frozen configuration, an empty dict for legacy runs, or None if missing.
        """
        live = self.active.get(run_id)
        if live and live[0].session_id == session_id:
            return deepcopy(live[0].data.get("configuration") or {})
        async with self.database().get_db() as session:
            row = (
                await session.execute(
                    select(WebChatSubagentRun.data["configuration"]).where(
                        WebChatSubagentRun.session_id == session_id,
                        WebChatSubagentRun.run_id == run_id,
                    )
                )
            ).one_or_none()
        return deepcopy(row[0] or {}) if row is not None else None

    def schedule_cleaned(self, umo: str, instance_ids: list[str]) -> None:
        """Record actual removal of agent instances without delaying synchronous tools.

        Args:
            umo: Runtime origin whose agents were removed.
            instance_ids: Exact lifetimes removed, protecting same-name replacements.
        """
        if not umo.startswith("webchat:") or not instance_ids:
            return
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            return

        async def clean():
            try:
                async with self.write_lock:
                    async with self.database().get_db() as session:
                        stored = (
                            await session.execute(
                                select(
                                    WebChatSubagentRun,
                                    func.substr(
                                        func.coalesce(
                                            func.nullif(
                                                WebChatSubagentRun.data[
                                                    "input_preview"
                                                ].as_string(),
                                                "",
                                            ),
                                            WebChatSubagentRun.data[
                                                "input_full"
                                            ].as_string(),
                                            "",
                                        ),
                                        1,
                                        200,
                                    ),
                                )
                                .options(defer(WebChatSubagentRun.data))
                                .where(
                                    WebChatSubagentRun.umo == umo,
                                    col(WebChatSubagentRun.agent_instance_id).in_(
                                        instance_ids
                                    ),
                                )
                            )
                        ).all()
                        rows = [row for row, _ in stored]
                        previews = {
                            row.run_id: preview or "" for row, preview in stored
                        }
                        for row in rows:
                            row.cleaned = True
                            row.revision += 1
                            live = self.active.get(row.run_id)
                            if live:
                                live[0].cleaned = True
                                row.revision = max(row.revision, live[0].revision + 1)
                                live[0].revision = row.revision
                                row.status = live[0].status
                            session.add(row)
                        await session.commit()
                        for row in rows:
                            live = self.active.get(row.run_id)
                            metadata = (
                                self.metadata(live[0])
                                if live
                                else self.metadata(row, previews[row.run_id])
                            )
                            self.publish(
                                f"session:{row.session_id}",
                                {"type": "changed", "data": metadata},
                            )
                            self.publish(
                                f"run:{row.session_id}:{row.run_id}",
                                {"type": "metadata", "data": metadata},
                            )
            except Exception:
                logger.exception("Failed to archive cleaned subagent invocations")

        task = loop.create_task(clean())
        self.tasks.add(task)
        task.add_done_callback(self.tasks.discard)

    async def delete_session(self, session_id: str, db=None) -> None:
        """Delete stored traces with their parent conversation.

        Args:
            session_id: Owned session or thread being deleted.
            db: Optional database supplied by the owning service.
        """
        async with self.write_lock:
            self.deleted_sessions.add(session_id)
            for run_id, (row, _) in list(self.active.items()):
                if row.session_id == session_id:
                    self.active.pop(run_id, None)
            async with (db or self.database()).get_db() as session:
                await session.execute(
                    delete(WebChatSubagentRun).where(
                        WebChatSubagentRun.session_id == session_id
                    )
                )
                await session.commit()
            self.legacy_indexed.discard(session_id)

    async def stream(self, session_id: str, run_id: str | None = None):
        """Yield initial and recoverable live snapshots for one owned page.

        Args:
            session_id: Parent session already checked by the API owner gate.
            run_id: Optional invocation; absent subscribes only to list metadata.

        Yields:
            JSON-ready snapshots, metadata changes and sequenced deltas.
        """
        key = f"run:{session_id}:{run_id}" if run_id else f"session:{session_id}"
        queue = asyncio.Queue(maxsize=256)
        self.subscribers[key].add(queue)
        try:
            yield {
                "type": "snapshot",
                "data": await self.get_run(session_id, run_id)
                if run_id
                else await self.list_runs(session_id),
            }
            while True:
                try:
                    event = await asyncio.wait_for(queue.get(), timeout=20)
                except asyncio.TimeoutError:
                    yield {"type": "heartbeat"}
                    continue
                if event["type"] == "resync":
                    yield {
                        "type": "snapshot",
                        "data": await self.get_run(session_id, run_id)
                        if run_id
                        else await self.list_runs(session_id),
                    }
                else:
                    yield event
        finally:
            self.subscribers[key].discard(queue)
            if not self.subscribers[key]:
                self.subscribers.pop(key, None)


subagent_progress = SubagentProgress()
