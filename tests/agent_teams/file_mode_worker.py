"""File capability scenarios using the shared real-pipeline worker."""

import asyncio
import json
import time
from pathlib import Path
from types import SimpleNamespace

import httpx
from sqlalchemy import event as sql_event
from sqlalchemy.orm import Session

from astrbot.core.agent_teams.assets import RoleAssetError, RoleAssetService
from astrbot.core.agent_teams.workflows import WorkflowService
from astrbot.core.db.po import AgentWorkflowCheckpoint
from astrbot.dashboard.services.agent_team_ports import build_ports_for_test


async def run_file_mode_scenario(
    folder: Path,
    endpoint: str,
    action: str,
    service: WorkflowService,
    roles: RoleAssetService,
    queue_manager,
) -> None:
    """Exercise public resources and launch through the actual event pipeline.

    Args:
        folder: Isolated durable state and public observations.
        endpoint: External model and sandbox filesystem endpoint.
        action: Initial execution or independent recovery.
        service: Real persisted workflow runtime.
        roles: Real role catalog and resolution.
        queue_manager: Actual WebChat delivery and collection queues.
    """
    case = json.loads((folder / "case.json").read_text(encoding="utf-8"))
    if case["settings"]["computer_use_runtime"] == "sandbox":

        class RemoteFilesystem:
            """Transport the sandbox API to an independent filesystem recorder."""

            async def write_file(self, **kwargs):
                """Write through the external filesystem API.

                Args:
                    **kwargs: Real sandbox filesystem arguments.

                Returns:
                    The external filesystem response.
                """
                async with httpx.AsyncClient() as client:
                    return (await client.post(endpoint + "/fs", json=kwargs)).json()

            async def exec(self, code, timeout=30):
                """Execute the file tool's sandbox Python transport.

                Args:
                    code: Python source generated by the actual file tool.
                    timeout: Sandbox execution limit.

                Returns:
                    The external sandbox response.
                """
                async with httpx.AsyncClient() as client:
                    return (
                        await client.post(
                            endpoint + "/python",
                            json={"code": code, "timeout": timeout},
                        )
                    ).json()

        # Only replace remote transport; tool classes and dispatch stay real.
        remote = RemoteFilesystem()

        async def remote_booter(plugin_context, session_id):
            """Return the external sandbox transport.

            Args:
                plugin_context: Actual tool context.
                session_id: Actual member session identity.

            Returns:
                Client implementing the sandbox filesystem API.
            """
            return SimpleNamespace(fs=remote, python=remote)

        from pytest import MonkeyPatch

        transport_patch = MonkeyPatch()
        transport_patch.setattr(
            "astrbot.core.tools.computer_tools.fs.get_booter", remote_booter
        )
        transport_patch.setattr(
            "astrbot.core.tools.computer_tools.patch_tool.get_booter", remote_booter
        )
    else:
        transport_patch = None
    crash_listeners = []
    try:
        observed = {"resources": await roles.get_resources()}
        if action != "start":
            run_id = json.loads(
                (folder / "kill-ready.json").read_text(encoding="utf-8")
            )["run_id"]
            before = await service.get_run("alice", run_id)
            if action == "recover":
                if case.get("revoke_tool"):
                    roles.core_lifecycle.provider_manager.llm_tools.get_builtin_tool(
                        case["revoke_tool"]
                    ).active = False
                await service.boot_sweep()
                try:
                    await service.recover_run("alice", run_id)
                except RoleAssetError as exc:
                    observed["recovery_error"] = {
                        "message": str(exc),
                        "fields": exc.fields,
                    }
                for _ in range(1000):
                    current = await service.get_run("alice", run_id)
                    if current["status"] not in {"pending", "running"}:
                        break
                    await asyncio.sleep(0.02)
            else:
                current = before
            observed.update(before=before, after=current)
            (folder / (action + ".json")).write_text(
                json.dumps(observed), encoding="utf-8"
            )
            return
        if case.get("crash_phase"):

            def before_flush(session, flush_context, instances):
                """Select an actual persistence boundary for external termination.

                Args:
                    session: Real persistence transaction.
                    flush_context: SQLAlchemy flush state.
                    instances: Explicit flush targets, if any.
                """
                for checkpoint in [*session.new, *session.dirty]:
                    if not isinstance(checkpoint, AgentWorkflowCheckpoint):
                        continue
                    response_id = (checkpoint.data.get("response") or {}).get("id")
                    if response_id not in {"plan-write", "plan-patch"}:
                        continue
                    if (
                        case["crash_phase"] == "response"
                        and checkpoint.phase == "response"
                    ):
                        session.info["file_boundary"] = checkpoint.run_id
                    if (
                        case["crash_phase"] == "unknown"
                        and checkpoint.phase == "tool_result"
                    ):
                        (folder / "kill-ready.json").write_text(
                            json.dumps({"run_id": checkpoint.run_id}), encoding="utf-8"
                        )
                        while True:
                            time.sleep(1)

            def after_commit(session):
                """Hold the committed plan until the parent kills this process.

                Args:
                    session: Completed real persistence transaction.
                """
                run_id = session.info.pop("file_boundary", None)
                if run_id:
                    (folder / "kill-ready.json").write_text(
                        json.dumps({"run_id": run_id}), encoding="utf-8"
                    )
                    while True:
                        time.sleep(1)

            crash_listeners = [
                ("before_flush", before_flush),
                ("after_commit", after_commit),
            ]
            for name, callback in crash_listeners:
                sql_event.listen(Session, name, callback)
        payload = {
            "definition": {
                "name": "File writer",
                "prompt": "File role prompt.",
                "persona_slot": "persona",
                "tools": case["tools"],
                "skills": [],
                "knowledge_bases": [],
            },
            "installation": {
                "bindings": {
                    "model": "model-original",
                    "persona": "writer",
                    **{name: name for name in case["tools"] or []},
                }
            },
        }
        observed["preview"] = await roles.preview_role(payload)
        role = await roles.save_role("alice", payload)
        (folder / "role.json").write_text(json.dumps(role), encoding="utf-8")
        if case["entry"] == "ordinary":
            ports = build_ports_for_test(queue_manager, "alice", lambda event: None)
            try:
                message_id = await ports.deliver(
                    "file-mode-chat", "Edit the isolated file."
                )
                observed["reply"], _ = await asyncio.wait_for(
                    ports.collect("file-mode-chat", message_id), 20
                )
            finally:
                await ports.close()
        else:
            definition = {
                "name": "File workflow",
                "tasks": [
                    {
                        "id": "write",
                        "name": "Write",
                        "member": "writer",
                        "role_id": role["role_id"],
                        "role_version": 1,
                        "task": "Edit the isolated file.",
                    }
                ],
                "edges": [],
            }
            if case["entry"] == "autonomous":
                coordinator = await roles.save_role(
                    "alice",
                    {
                        "definition": {
                            "name": "Coordinator",
                            "prompt": "Coordinate and submit the file result.",
                            "tools": [],
                            "skills": [],
                            "knowledge_bases": [],
                        },
                        "installation": {"bindings": {"model": "model-original"}},
                    },
                )
                definition = {
                    "kind": "autonomous",
                    "name": "File team",
                    "coordinator": {
                        "role_id": coordinator["role_id"],
                        "role_version": 1,
                    },
                    "allowed_roles": [{"role_id": role["role_id"], "role_version": 1}],
                    "max_parallel": 1,
                }
            asset = await service.save_asset("alice", {"definition": definition})
            observed["readiness"] = await service.check_readiness(
                "alice", asset["asset_id"]
            )
            try:
                run = await service.start_run(
                    "alice",
                    asset["asset_id"],
                    {
                        "version": 1,
                        "inputs": {"goal": "Edit the isolated file."}
                        if case["entry"] == "autonomous"
                        else {},
                    },
                )
            except RoleAssetError as exc:
                observed["start_error"] = {"message": str(exc), "fields": exc.fields}
            else:
                if case.get("old_attempt"):
                    for _ in range(1000):
                        root = await service.get_run("alice", run["run_id"])
                        child = root["tasks"][0]
                        if child["status"] == "awaiting_result":
                            break
                        await asyncio.sleep(0.02)
                    original = await service.get_run("alice", child["run_id"])
                    assert original["status"] == "awaiting_result", original
                    (folder / "old-attempt.json").write_text(
                        json.dumps(original), encoding="utf-8"
                    )
                    await service.retry_task(
                        "alice",
                        child["run_id"],
                        {
                            "request_id": "retry-file",
                            "attempt_id": original["state"]["attempt_id"],
                            "input_policy": "original",
                        },
                    )
                if case.get("change_after_launch"):
                    roles.core_lifecycle.astrbot_config_mgr.confs["default"][
                        "provider_settings"
                    ]["file_tool_mode"] = case["change_after_launch"]
                for _ in range(1000):
                    run = await service.get_run("alice", run["run_id"])
                    if run["status"] not in {"pending", "running"}:
                        break
                    await asyncio.sleep(0.02)
                observed["run"] = run
        (folder / "observed.json").write_text(json.dumps(observed), encoding="utf-8")
    finally:
        for name, callback in crash_listeners:
            sql_event.remove(Session, name, callback)
        if transport_patch:
            transport_patch.undo()
