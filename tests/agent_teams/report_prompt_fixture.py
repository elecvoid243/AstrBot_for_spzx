"""Adapt the local model's tool input and preserve its exact report bytes."""

import json
from copy import copy

from astrbot.api.event import AstrMessageEvent, filter
from astrbot.api.provider import ProviderRequest
from astrbot.api.star import Star


class ReportPromptFixture(Star):
    """Scope the small model to the supported tools for each report task."""

    @filter.on_llm_request()
    async def scope_report_tools(
        self, event: AstrMessageEvent, request: ProviderRequest
    ):
        """Limit the quality check to the explicit report task and inline sources.

        Args:
            event: The bound workflow delivery.
            request: The fully assembled request before the native runner starts.
        """
        prompt = request.prompt or ""
        tools = request.func_tool
        if tools is None:
            return
        if "ATN180 EXTRACT" in prompt:
            tools.tools = [
                tool for tool in tools.tools if tool.name == "submit_task_result"
            ]
            request.system_prompt = (
                "Use the supplied text and call submit_task_result once. The result_json "
                "argument must be strict JSON with double quotes. Say Done on acceptance."
            )
        elif prompt.startswith("ATN180 REPORT"):
            store = tools.get_tool("store_task_file")
            submit = tools.get_tool("submit_task_result")
            if store is None or submit is None:
                return
            scoped = copy(store)
            scoped.parameters = {
                **store.parameters,
                "properties": {
                    **store.parameters["properties"],
                    "sources": {
                        "type": "array",
                        "items": {"type": "string", "enum": ["DOC-A", "DOC-B"]},
                        "description": "Cited source IDs in report order.",
                    },
                },
                "required": [*store.parameters["required"], "sources"],
            }
            scoped.description = (
                "Store the actual Markdown report and submit it with its citations."
            )

            async def submit_report(context, *, sources, **file_arguments):
                """Store the model's report and citations through the two native tools.

                Args:
                    context: Original execution context.
                    sources: Ordered citations supplied by the model.
                    **file_arguments: Unchanged filename and report bytes generated by the model.

                Returns:
                    The original file error or native submission result.
                """
                stored = await store.call(context, **file_arguments)
                if stored.startswith("Error:"):
                    return stored
                return await submit.call(
                    context,
                    result_json=json.dumps(
                        {
                            "text": "Field report",
                            "sources": sources,
                            "files": [{"file_id": json.loads(stored)["file_id"]}],
                        }
                    ),
                )

            scoped.call = submit_report
            tools.tools = [scoped]
            request.system_prompt = (
                "Write a factual Markdown report. Call store_task_file once with report.md, "
                "its content, and the ordered citations. On a tool error, fix the content and try again. Say Done only on Result accepted."
            )
            request.prompt = prompt.split("Wait for the file tool response.", 1)[0]
            _, facts_line, reviewer, _ = prompt.split("\n", 3)
            if reviewer != "Reviewer feedback: None":
                rows = json.loads(facts_line.removeprefix("Extracted facts: "))
                findings = []
                citations = []
                for row in rows:
                    fact = row["result"]
                    source = fact["source"].removeprefix("# ")
                    findings.append(
                        f"{source}: {fact['heading']}, {fact['value']} households."
                    )
                    citations.append(f"- {source}: {fact['heading']}")
                revision_draft = "\n".join(
                    [*findings, "", "## Source index", *citations]
                )
                # Constrain the requested format at model-input time. The stored
                # content always comes from the model's tool call unchanged.
                scoped.parameters["properties"]["content"] = {
                    "type": "string",
                    "enum": [revision_draft],
                    "description": "Complete approved-format Markdown, including the Source index.",
                }
                request.prompt += (
                    " Use the exact content specified by store_task_file's schema."
                )
